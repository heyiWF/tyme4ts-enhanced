// Developer examples are compiled against the actual API and executed for their output.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import ts from 'typescript';
import * as api from '../dist/lib/index.mjs';
const fields=JSON.parse(readFileSync('scripts/fixtures/api-fields.json','utf8'));
const names=Object.keys(api);
const importsFor=expr=>names.filter(n=>new RegExp(`\\b${n}\\b`).test(expr));
const base='const a = DayAlmanac.fromYmd(2025, 4, 3);';
const values=[];
for(const f of fields) {
    const imports=[...new Set(['DayAlmanac',...importsFor(f.expression)])];
    const value=Function(...imports,`${base}\nreturn (${f.expression});`)(...imports.map(n=>api[n]));
    let display='value';
    if(value===null || value===undefined) display="value?.toString() ?? '无'";
    else if(Array.isArray(value)) {
        if(value.length && value[0] && typeof value[0]==='object' && value[0].constructor!==Object) {
            if(typeof value[0].getStart==='function') display='value.map(p => ({name:p.getName(), start:p.getStart().toString(), end:p.getEnd().toString()}))';
            else display='value.map(item => item.toString())';
        }
    } else if(typeof value==='object' && value.constructor!==Object) {
        display=typeof value.getNames==='function'?'value.getNames()':typeof value.getEntries==='function'?'value.getEntries().map(e => e.getName())':'value.toString()';
    }
    // Nullable APIs must remain safe when the reader changes the sample date.
    if(['神明诞辰','日本年号','节假日'].includes(f.title)) display="value?.toString() ?? '无'";
    const output=Function('value',`return ${display};`)(value);
    values.push({...f,imports,display,output:typeof output==='string'?output:JSON.stringify(output,null,2)});
}
const guideHtml=readFileSync('docs/index.html','utf8').split('<script type="module">')[0];
const guides=[...guideHtml.matchAll(/<pre class="api-code"><code>([\s\S]*?)<\/code><\/pre>/g)].map(m=>m[1].replace(/&gt;/g,'>').replace(/&lt;/g,'<').replace(/&amp;/g,'&'));
const guideImports=[];
const guideBodies=guides.map(code=>code.replace(/import\s*\{([^}]+)\}\s*from\s*'tyme4ts-enhanced';?/g,(_,list)=>{
    guideImports.push(...list.split(',').map(s=>s.trim()));return '';
}));
for(const body of guideBodies) Function(...names,'console',body)(...names.map(n=>api[n]),{log(){}});
const imports=[...new Set([...values.flatMap(f=>f.imports),...guideImports])].sort();
let source=`import {${imports.join(',')}} from './lib';\n`;
values.forEach((f,i)=>{source+=`function example${i}() {\n${base}\nconst value = ${f.expression};\nconsole.log(${f.display});\n}\n`;});
guideBodies.forEach((body,i)=>{source+=`function guide${i}() {\n${body}\n}\n`;});
const file=resolve('__api_docs__.ts');
const options={target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext,moduleResolution:ts.ModuleResolutionKind.Node10,strict:true,skipLibCheck:true,noEmit:true};
const host=ts.createCompilerHost(options),oldGet=host.getSourceFile.bind(host);
host.getSourceFile=(path,...args)=>resolve(path)===file?ts.createSourceFile(file,source,options.target,true):oldGet(path,...args);
const program=ts.createProgram([file],options,host);
const diagnostics=ts.getPreEmitDiagnostics(program);
if(diagnostics.length) throw Error(ts.formatDiagnosticsWithColorAndContext(diagnostics,{getCurrentDirectory:()=>process.cwd(),getCanonicalFileName:f=>f,getNewLine:()=> '\n'}));
const checker=program.getTypeChecker();
for(const node of program.getSourceFile(file).statements) {
    if(!ts.isFunctionDeclaration(node) || !node.name.text.startsWith('example')) continue;
    const i=Number(node.name.text.slice(7));
    const value=node.body.statements.find(s=>ts.isVariableStatement(s)&&s.declarationList.declarations[0].name.getText()==='value').declarationList.declarations[0];
    values[i].returns=checker.typeToString(checker.getTypeAtLocation(value.name),undefined,ts.TypeFormatFlags.NoTruncation);
    const f=values[i];
    f.code=`import {${f.imports.join(', ')}} from 'tyme4ts-enhanced';\n\n${base}\nconst value = ${f.expression};\n// 返回类型：${f.returns}\nconsole.log(${f.display});`;
    delete f.imports;delete f.display;
}
writeFileSync('docs/api-reference.js','// Generated by scripts/build-api-docs.mjs. Do not edit.\nexport const API_FIELDS = '+JSON.stringify(values,null,2)+';\n');
console.log(`Developer reference: ${values.length} field snippets + ${guides.length} guide examples typechecked and executed`);
